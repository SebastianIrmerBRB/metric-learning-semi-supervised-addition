"""Turn collected tracking data into tables meant for human eyes.

Three formats, because they get read in three places: Markdown for a terminal or
a pull request, CSV for a spreadsheet, and LaTeX ``booktabs`` for the thesis.
The numbers are identical in all three; only the escaping differs.

Every table reports the **baseline and the delta**, not just the final value. A
final effective rank of 12 means nothing on its own -- the question is always
whether training moved it, and from what.

Examples::

    python evaluate/tables.py --root logs/phase_1 --out evaluate_out
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from evaluate import common


def _format(value, digits: int = 4) -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "--"
    if isinstance(value, float):
        if abs(value) >= 1000:
            return f"{value:,.0f}"
        return f"{value:.{digits}f}"
    return str(value)


def _arrow(metric: str, delta: float) -> str:
    """Say whether a change is an improvement, where the metric has a direction."""

    if pd.isna(delta) or abs(delta) < 1e-12:
        return "="
    better = common.HIGHER_IS_BETTER.get(metric)
    if better is None:
        return "+" if delta > 0 else "-"
    improved = delta > 0 if better else delta < 0
    return "up" if improved else "down"


def summary_markdown(summary: pd.DataFrame) -> str:
    """One section per metric group, one row per run."""

    lines = ["# Epoch tracking summary", ""]
    lines.append(
        "`baseline` is epoch -1 (before any optimizer step), `final` the last "
        "tracked epoch, both averaged over the run's folds. `+/-` is the "
        "standard deviation across folds."
    )
    lines.append("")
    ragged = summary[summary.get("final_epoch_spread", 0) > 0]
    if not ragged.empty:
        runs = sorted(set(ragged["run"]))
        lines.append(
            "> **Note: ragged folds.** These runs have folds whose last tracked epoch "
            f"differs, so `final` averages unlike epochs: {', '.join(runs)}. This is "
            "normal when early stopping ends each fold at its own epoch, and also "
            "happens when a run is interrupted mid-fold. The per-epoch curves are "
            "unaffected; only the `final` column mixes epochs, so read the per-run "
            "tables when that matters."
        )
        lines.append("")
    for group, metrics in common.METRIC_GROUPS.items():
        present = [m for m in metrics if m in set(summary["metric"])]
        if not present:
            continue
        lines.append(f"## {group.capitalize()}")
        lines.append("")
        lines.append("| Run | Metric | Folds | Baseline | Final | Delta | |")
        lines.append("| --- | --- | ---: | ---: | ---: | ---: | :-: |")
        for metric in present:
            rows = summary[summary["metric"] == metric]
            for _, row in rows.iterrows():
                lines.append(
                    "| {run} | {label} | {folds} | {base} +/- {bstd} | "
                    "{final} +/- {fstd} | {delta} | {arrow} |".format(
                        run=row["run"],
                        label=row["metric_label"],
                        folds=int(row["folds"]),
                        base=_format(row["baseline"]),
                        bstd=_format(row["baseline_std"], 3),
                        final=_format(row["final"]),
                        fstd=_format(row["final_std"], 3),
                        delta=_format(row["delta"]),
                        arrow=_arrow(metric, row["delta"]),
                    )
                )
        lines.append("")
    return "\n".join(lines)


def summary_latex(summary: pd.DataFrame) -> str:
    """A booktabs table per metric group, ready to \\input into the thesis."""

    blocks = []
    for group, metrics in common.METRIC_GROUPS.items():
        present = [m for m in metrics if m in set(summary["metric"])]
        if not present:
            continue
        lines = [
            "% Generated by evaluate/tables.py -- do not edit by hand.",
            "\\begin{table}[t]",
            "  \\centering",
            f"  \\caption{{{group.capitalize()} structure across training. "
            "Baseline is epoch $-1$; values are means over folds.}}",
            f"  \\label{{tab:epoch-tracking-{group}}}",
            "  \\begin{tabular}{llrrr}",
            "    \\toprule",
            "    Run & Metric & Baseline & Final & $\\Delta$ \\\\",
            "    \\midrule",
        ]
        for metric in present:
            for _, row in summary[summary["metric"] == metric].iterrows():
                run = str(row["run"]).replace("_", "\\_").replace("·", "\\textperiodcentered{}")
                label = str(row["metric_label"]).replace("_", "\\_")
                lines.append(
                    f"    {run} & {label} & {_format(row['baseline'])} & "
                    f"{_format(row['final'])} & {_format(row['delta'])} \\\\"
                )
        lines += [
            "    \\bottomrule",
            "  \\end{tabular}",
            "\\end{table}",
            "",
        ]
        blocks.append("\n".join(lines))
    return "\n".join(blocks)


def per_run_markdown(epochs: pd.DataFrame, metrics: list[str], run_id: str) -> str:
    """The full epoch-by-epoch curve for one run, folds averaged."""

    frame = epochs[epochs["run_id"] == run_id]
    if frame.empty:
        return ""
    name = frame["run"].iloc[0]
    present = [m for m in metrics if m in frame.columns and frame[m].notna().any()]
    averaged = frame.groupby("epoch", as_index=False)[present].mean(numeric_only=True)
    # Folds that early-stop at different epochs leave the late rows resting on
    # fewer folds, and a one-fold "mean" reads exactly like a four-fold one. The
    # count is carried per row so a late spike cannot be mistaken for a trend.
    fold_counts = frame.groupby("epoch")["fold"].nunique()
    total_folds = frame["fold"].nunique()
    lines = [f"# {name}", "", f"`run_id`: `{run_id}`  ", f"folds: {total_folds}", ""]
    header = ["Epoch", "Folds"] + [common.METRIC_LABELS.get(m, m) for m in present]
    lines.append("| " + " | ".join(header) + " |")
    lines.append("| " + " | ".join(["---"] * len(header)) + " |")
    for _, row in averaged.iterrows():
        epoch = int(row["epoch"])
        contributing = int(fold_counts.get(epoch, 0))
        cells = [f"**{epoch}** (baseline)" if epoch == common.BASELINE_EPOCH else str(epoch)]
        cells.append(
            str(contributing) if contributing == total_folds else f"**{contributing}**"
        )
        cells += [_format(row[m]) for m in present]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def write_tables(collected: dict, out: Path) -> list[Path]:
    tables_dir = out / "tables"
    per_run_dir = tables_dir / "per_run"
    per_run_dir.mkdir(parents=True, exist_ok=True)

    summary = collected["summary"]
    written = []
    if summary.empty:
        return written

    markdown_path = tables_dir / "summary.md"
    markdown_path.write_text(summary_markdown(summary), encoding="utf-8")
    written.append(markdown_path)

    csv_path = tables_dir / "summary.csv"
    summary.to_csv(csv_path, index=False)
    written.append(csv_path)

    latex_path = tables_dir / "summary.tex"
    latex_path.write_text(summary_latex(summary), encoding="utf-8")
    written.append(latex_path)

    epochs = collected["epochs"]
    for run_id in epochs["run_id"].unique():
        text = per_run_markdown(epochs, collected["metrics"], run_id)
        if not text:
            continue
        path = per_run_dir / f"{run_id}.md"
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def main() -> None:
    from evaluate.collect import collect

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=Path("evaluate_out"))
    args = parser.parse_args()

    written = write_tables(collect(args.root, args.out), args.out)
    for path in written:
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
